import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const sandbox={window:{},crypto:webcrypto,Date,console};
vm.createContext(sandbox);vm.runInContext(fs.readFileSync('verification-audit.js','utf8'),sandbox);
const A=sandbox.window.SOUTU_VERIFICATION_AUDIT;
const plain=x=>JSON.parse(JSON.stringify(x));
const root={id:'root',title:'Original',lineageKey:'f|root',kind:'provenance-lineage',lineage:{familyId:'f',role:'candidate-root',directionState:'candidate-root'}};
const review={status:'verified',note:'核对来源',reviewer:'Alice',reason:'比对原始页面',finalized:true};
const first=A.append(root,review).evidence;
assert.equal(first.verificationHistory.length,1);
assert.equal(first.verificationHistory[0].before.status,'needs-review');
assert.equal(first.verification.finalized,true);
assert.deepEqual(plain(first.lineage),root.lineage,'machine inference preserved');
assert.equal(A.append(first,{...review,reviewer:'Bob',reason:'重复提交'}).changed,false,'no-op is not a review');
assert.throws(()=>A.append(root,{...review,reviewer:''}),/reviewer-and-reason/);
assert.throws(()=>A.append(root,{...review,reason:''}),/reviewer-and-reason/);
assert.throws(()=>A.append(root,{...review,status:'invalid'}),/invalid-status/);
const second=A.append(first,{...review,status:'rejected',note:'找到较早版本',conflict:true,reviewer:'Bob',reason:'时间证据冲突'}).evidence;
assert.equal(second.verificationHistory.length,2);
assert.deepEqual(plain(second.verificationHistory[0]),plain(first.verificationHistory[0]));
const undone=A.append(second,{action:'undo',reviewer:'Silvia',reason:'重新核对日期'}).evidence;
assert.equal(undone.verification.status,'verified');assert.equal(undone.verification.conflict,false);
assert.equal(undone.verificationHistory.length,3);
assert.equal(undone.verificationHistory[2].targetEventId,second.verificationHistory[1].id);
const restored=A.append(undone,{action:'restore',targetEventId:second.verificationHistory[1].id,reviewer:'Silvia',reason:'恢复第二次裁定'}).evidence;
assert.equal(restored.verification.status,'rejected');assert.equal(restored.verificationHistory.length,4);
assert.throws(()=>A.append(restored,{...review,expectedRevision:A.revision(first)}),/stale-review/);
assert.throws(()=>A.append(first,{action:'restore',targetEventId:'missing',reviewer:'A',reason:'x'}),/no-restore-target/);
const legacy={...root,verification:{status:'inconclusive',note:'旧备注',reviewedAt:123,reviewer:'旧审核人'}};
const migrated=A.append(legacy,review).evidence;
assert.equal(migrated.verificationHistory.length,2);assert.equal(migrated.verificationHistory[0].action,'legacy-baseline');
assert.equal(migrated.verificationHistory[0].before,null);
assert.match(migrated.verificationHistory[0].reason,/不可恢复/);
const canonical=A.canonical({...root,id:'case-copy'},[restored]);
assert.equal(canonical.id,'case-copy');assert.equal(canonical.verificationHistory.length,4);
assert.deepEqual(plain(A.summary([restored])),{events:4,finalized:1,reversals:2});
const bad=plain(restored);bad.verificationHistory[0].reason='different';
assert.throws(()=>A.canonical(restored,[bad]),/audit-event-conflict/);
assert.notEqual(A.keyOf({id:'one'}),A.keyOf({id:'two'}),'ordinary evidence identities cannot collapse');
const csv=A.csv([{...restored,title:'=HYPERLINK("evil")'}]);
assert.match(csv,/'=HYPERLINK/);assert.match(csv,/恢复第二次裁定/);
assert.equal(A.payload([restored]).schema,'soutu-pro.verification-audit.v1');

// Exercise the real persistence adapter, including all-or-none validation and rollback.
const data=new Map(),storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
const doc={readyState:'loading',addEventListener(){},getElementById(){return null},querySelector(){return null},querySelectorAll(){return[]}};
sandbox.document=doc;sandbox.localStorage=storage;sandbox.sessionStorage=storage;
sandbox.window.SOUTU_V9={refreshEvidence(){}};
vm.runInContext(fs.readFileSync('evidence-verification.js','utf8'),sandbox);
const V=sandbox.window.SOUTU_EVIDENCE_VERIFICATION,ek='soutu-pro-v9-evidence',ck='soutu-pro-v9-cases';
const seed=()=>{storage.setItem(ek,JSON.stringify([root,{id:'ordinary',note:'untouched'}]));storage.setItem(ck,JSON.stringify([{id:'case1',evidence:[{...root,id:'copy'}]},{id:'case2',evidence:[{...root,id:'other-copy'}]}]))};
seed();let result=V.applyVerificationChanges([{id:'root',...review}],{reload:false});assert.equal(result.ok,true);
let stored=JSON.parse(storage.getItem(ek)),cases=JSON.parse(storage.getItem(ck));
assert.equal(stored[0].verificationHistory.length,1);assert.equal(stored[1].note,'untouched');
for(const c of cases){assert.equal(c.evidence[0].verification.status,'verified');assert.deepEqual(c.evidence[0].verificationHistory,stored[0].verificationHistory);assert.equal(c.verificationAuditSummary.events,1)}
const beforeE=storage.getItem(ek),beforeC=storage.getItem(ck);
result=V.applyVerificationChanges([{id:'root',...review},{id:'missing',...review}],{reload:false});assert.equal(result.reason,'no-match');assert.equal(storage.getItem(ek),beforeE);assert.equal(storage.getItem(ck),beforeC);
result=V.applyVerificationChanges([{id:'root',...review,status:'rejected',expectedRevision:A.revision(root)}],{reload:false});assert.equal(result.reason,'stale-review');assert.equal(storage.getItem(ek),beforeE);
let fail=true;storage.setItem=(k,v)=>{if(k===ck&&fail){fail=false;throw new Error('quota')}data.set(k,v)};
result=V.applyVerificationChanges([{id:'root',...review,status:'rejected'}],{reload:false});assert.equal(result.reason,'case-storage');assert.equal(storage.getItem(ek),beforeE);assert.equal(storage.getItem(ck),beforeC);

for(const file of ['config.js','build-static.mjs','sw.js'])assert(fs.readFileSync(file,'utf8').includes('verification-audit.js'),`${file}: audit module integration`);
assert(fs.readFileSync('.github/workflows/e2e.yml','utf8').includes('tests/verification-audit.spec.mjs'));
console.log('Verification audit regression passed: append, no-op, undo/restore, migration, stale edits, Case sync, rollback, identity and export');
